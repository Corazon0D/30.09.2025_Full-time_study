# Задача (list comprehension)
"""
1. строка s = ''
2. множества s = set()
3. спискиs s = []
4. кортежи s = ()
5. словари - предстоит
"""
s = 'лето осень зима весна'

# Внести их в строки в двойных кавычках
# s = ["лето", "осень", "зима", "весна"]   надо так сделать
lst = s.split()
temp = [f'\"{i}\"' for i in s.split()]
lst = ', '.join(temp)

print(f'[{lst}]')